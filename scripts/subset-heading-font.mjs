#!/usr/bin/env node
/**
 * Build the Chinese heading font.
 *
 * Headings are set in Noto Serif SC. The full simplified-Chinese file is
 * 1.5 MB and every visitor would download it for a few dozen characters.
 * This script collects the characters that headings actually use (titles,
 * h1-h4 in notes and pages, and any Chinese in the theme's own files) and
 * writes a font holding only those, about a tenth of the size.
 *
 * Runs before `npm run dev` and `npm run build`. Output is not committed:
 *   src/styles/generated/heading-font.css
 *   src/styles/generated/noto-serif-sc-600-headings.woff2
 *
 * A character that is missing (text created in the browser, say) falls
 * back to the next font in the stack, so nothing breaks; it just is not
 * in the web font.
 */

import { readFile, writeFile, mkdir, readdir } from 'node:fs/promises';
import { existsSync } from 'node:fs';
import { join, dirname, extname } from 'node:path';
import { fileURLToPath } from 'node:url';
import subsetFont from 'subset-font';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const SOURCE = join(ROOT, 'node_modules/@fontsource/noto-serif-sc/files/noto-serif-sc-chinese-simplified-600-normal.woff2');
const OUT_DIR = join(ROOT, 'src/styles/generated');
const FONT_FILE = 'noto-serif-sc-600-headings.woff2';

// CJK ideographs, CJK punctuation, full-width forms. Latin stays with Source Serif 4.
const WANTED = /[⺀-⿟　-〿㐀-䶿一-鿿豈-﫿︰-﹏＀-￯]/g;
const UNICODE_RANGE = 'U+2E80-2FDF, U+3000-303F, U+3400-4DBF, U+4E00-9FFF, U+F900-FAFF, U+FE30-FE4F, U+FF00-FFEF';

async function walk(dir, out = []) {
  if (!existsSync(dir)) return out;
  for (const entry of await readdir(dir, { withFileTypes: true })) {
    if (entry.name.startsWith('.') || entry.name === 'node_modules' || entry.name === 'generated') continue;
    const path = join(dir, entry.name);
    if (entry.isDirectory()) await walk(path, out);
    else out.push(path);
  }
  return out;
}

/** Text of every title and h1-h4 in a Markdown file that may hold raw HTML. */
function headingText(source) {
  const parts = [];
  for (const m of source.matchAll(/^(?:title|description):\s*(.*)$/gm)) parts.push(m[1]);
  const body = source
    .replace(/```[\s\S]*?```/g, '')
    .replace(/<(style|script|pre|code)\b[\s\S]*?<\/\1>/gi, '');
  for (const m of body.matchAll(/^#{1,4}\s+(.*)$/gm)) parts.push(m[1]);
  for (const m of body.matchAll(/<h[1-4]\b[^>]*>([\s\S]*?)<\/h[1-4]>/gi)) parts.push(m[1].replace(/<[^>]+>/g, ''));
  // Embedded notes also set other elements in the heading font (see their CSS):
  // anything they mark as a title or a big number is cheap to include.
  for (const m of body.matchAll(/class="[^"]*\b(?:title|kicker|hd|lede|big)\b[^"]*"[^>]*>([^<]{1,80})</gi)) parts.push(m[1]);
  return parts.join('');
}

const chars = new Set('，。、；：？！“”‘’（）《》「」『』【】—…·｜');
const contentFiles = (await walk(join(ROOT, 'src/content'))).concat(await walk(join(ROOT, 'drafts')));
for (const file of contentFiles) {
  if (!['.md', '.mdx'].includes(extname(file))) continue;
  for (const c of headingText(await readFile(file, 'utf8')).match(WANTED) ?? []) chars.add(c);
}
// Chinese written directly in components, layouts, pages and the site config.
for (const dir of ['src/components', 'src/layouts', 'src/pages']) {
  for (const file of await walk(join(ROOT, dir))) {
    for (const c of (await readFile(file, 'utf8')).match(WANTED) ?? []) chars.add(c);
  }
}
for (const c of (await readFile(join(ROOT, 'src/config.ts'), 'utf8')).match(WANTED) ?? []) chars.add(c);

const text = [...chars].sort().join('');
const subset = await subsetFont(await readFile(SOURCE), text, { targetFormat: 'woff2' });

await mkdir(OUT_DIR, { recursive: true });
await writeFile(join(OUT_DIR, FONT_FILE), subset);
await writeFile(
  join(OUT_DIR, 'heading-font.css'),
  `/* Generated by scripts/subset-heading-font.mjs. Do not edit. */
@font-face {
  font-family: 'Noto Serif SC';
  font-style: normal;
  font-display: swap;
  font-weight: 600;
  src: url(./${FONT_FILE}) format('woff2');
  unicode-range: ${UNICODE_RANGE};
}
`
);
console.log(`heading font: ${chars.size} characters, ${Math.round(subset.length / 1024)} KB`);
